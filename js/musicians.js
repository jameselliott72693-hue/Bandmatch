const BY_ID = new Map(MUSICIANS.map((person) => [person.id, person]));

export function getMusician(id) {
  return BY_ID.get(id) || null;
}

export function roleLabel(role) {
  return ROLE_LABEL[role] || role;
}

function clamp01(n) {
  return Math.min(1, Math.max(0, Number(n) || 0));
}

function slug(name) {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 32);
}

const TEMPO_PRESET = {
  slow: [72, 96],
  mid: [96, 120],
  fast: [124, 152],
};

const TRAIT_PRESET = {
  swing: { straight: 0.08, swing: 0.74 },
  density: { sparse: 0.28, balanced: 0.52, busy: 0.78 },
  weight: { light: 0.28, medium: 0.52, heavy: 0.8 },
};

const TONE_PRESET = {
  clean: { drive: 0.08, brightness: 0.74 },
  warm: { drive: 0.28, brightness: 0.48 },
  driven: { drive: 0.78, brightness: 0.4 },
};

export function createCustomMusician(input) {
  const name = String(input.name || "")
    .replace(/[<>]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 40);
  const role = ROLE_IDS.includes(input.role) ? input.role : "guitar";
  const genres = (Array.isArray(input.genres) ? input.genres : [])
    .filter((genre) => GENRE_IDS.includes(genre))
    .slice(0, 3);
  const safeGenres = genres.length ? genres : ["rock"];
  let tempoMin = Number(input.tempoMin);
  let tempoMax = Number(input.tempoMax);
  if (!Number.isFinite(tempoMin) || !Number.isFinite(tempoMax)) {
    const preset = TEMPO_PRESET[input.tempo] || TEMPO_PRESET.mid;
    tempoMin = preset[0];
    tempoMax = preset[1];
  }
  tempoMin = Math.round(Math.min(180, Math.max(60, tempoMin)));
  tempoMax = Math.round(Math.min(180, Math.max(tempoMin, tempoMax)));
  const swing = clamp01(input.swing ?? TRAIT_PRESET.swing[input.feel] ?? 0.08);
  const density = clamp01(input.density ?? TRAIT_PRESET.density[input.densityId] ?? 0.52);
  const weight = clamp01(input.weight ?? TRAIT_PRESET.weight[input.weightId] ?? 0.52);
  const tone = TONE_PRESET[input.tone] || null;
  const drive = clamp01(input.drive ?? tone?.drive ?? 0.28);
  const brightness = clamp01(input.brightness ?? tone?.brightness ?? 0.5);
  const feel = [];
  feel.push(swing >= 0.5 ? "swing" : "straight");
  if (density <= 0.34) feel.push("sparse");
  if (weight >= 0.66) feel.push("heavy");
  if (safeGenres.some((genre) => ["funk", "soul", "r&b", "hip-hop", "disco"].includes(genre))) {
    feel.push("groove");
  }
  const feelWord = swing >= 0.5 ? "swung" : "straight";
  const densityWord = density <= 0.34 ? "sparse" : density >= 0.66 ? "busy" : "medium";
  const toneWord = drive >= 0.6 ? "driven" : drive >= 0.3 ? "warm" : "clean";
  const id = `custom:${slug(name) || "player"}:${role}:${[
    safeGenres.join("+"),
    tempoMin,
    tempoMax,
    swing.toFixed(2),
    density.toFixed(2),
    weight.toFixed(2),
    brightness.toFixed(2),
    drive.toFixed(2),
  ].join("-")}`;
  return {
    id,
    name: name || "Custom player",
    roles: [role],
    genres: safeGenres,
    tempoMin,
    tempoMax,
    swing,
    density,
    weight,
    brightness,
    drive,
    feel,
    tendencies: [
      `${feelWord} ${densityWord} phrasing`,
      `${toneWord} tone in a ${GENRE_LABEL[safeGenres[0]].toLowerCase()} pocket`,
    ],
    custom: true,
  };
}

